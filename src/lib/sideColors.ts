// Цвета сторон на светлом фоне — пульт оператора (карточка боя).
//
// ЗАКРЕПЛЕНО, и это главное в этом файле: **участник 1 — синий и слева,
// участник 2 — красный и справа**. Та же привязка, что на табло
// (`components/display/boardStyle.ts`), потому что судья за пультом и зал
// смотрят на один и тот же бой: если стороны разойдутся, судья начислит укол
// не тому — и увидит это только по табло.
//
// Значения при этом другие и одним набором быть не могут: табло тёмное, пульт
// светлый, и цвет, читаемый на `#0b0d12`, на белом теряется (и наоборот).
// Общее у двух файлов — не палитра, а распределение сторон.
//
// Цвет здесь дублирует позицию, а не заменяет её: сторона читается и по
// «слева/справа», и по имени в панели. Это важно для дальтоников — самая
// частая форма как раз краснозелёная, но красный и синий на светлом различимы
// не всегда, поэтому цвет остаётся вторым признаком, а не единственным.

export interface SideTone {
  /** Имя стороны, её счёт и акценты. Достаточно тёмный для текста на белом. */
  text: string
  /** Полоса, отбивающая блок стороны. Совпадает с `line` табло. */
  line: string
  /** Заливка блока стороны. */
  wash: string
  /** Граница блока и кнопок стороны. */
  border: string
}

/** Участник 1 — синий, слева. */
export const SIDE1: SideTone = {
  text: '#1558b0',
  line: '#2563eb',
  wash: '#eff5ff',
  border: '#c3daff',
}

/** Участник 2 — красный, справа. */
export const SIDE2: SideTone = {
  text: '#b3261e',
  line: '#dc2626',
  wash: '#fff3f2',
  border: '#f2cbc7',
}

export function sideTone(side: 1 | 2): SideTone {
  return side === 1 ? SIDE1 : SIDE2
}
